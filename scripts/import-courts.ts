/**
 * Court import: OSM Overpass JSON -> normalized courts -> SQL seed.
 * Usage: pnpm courts:import [input.json] [out.sql] [--no-cluster]
 * By default nearby pitches (<=35 m, same access) are merged into one court site.
 * Offline only. Never queries Overpass; see full-court-check.ts for the geometry query.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { summarize } from '@vk/core';
import { loadCourts, loadSites } from './lib.js';

const args = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const input = args[0] ?? 'data/osm_la_county_basketball_pitches.json';
const out = args[1] ?? 'supabase/seed/courts.sql';
const cluster = !process.argv.includes('--no-cluster');

const q = (s: string | null) => (s === null ? 'null' : `'${s.replace(/'/g, "''")}'`);
const n = (x: number | null) => (x === null ? 'null' : String(x));

const { sites, pitches, skipped } = cluster
  ? loadSites(input)
  : { ...(() => { const r = loadCourts(input); return { sites: r.courts.map((c) => ({ ...c, memberCount: 1, memberOsmIds: [`${c.osmType}/${c.osmId}`] })), pitches: r.courts.length }; })(), skipped: 0 };
const arr = (xs: string[]) => `'{${xs.map((x) => `"${x}"`).join(',')}}'`;
const rows = sites.map(
  (c) =>
    `(${q(c.osmType)},${c.osmId},${q(c.name)},${c.lat},${c.lng},${q(c.courtType)},${q(c.typeSource)},${n(c.hoops)},${n(c.areaM2)},${q(c.access)},${c.memberCount},${arr(c.memberOsmIds)})`,
);

const sql =
  `-- Generated by scripts/import-courts.ts from ${input}. Data: OpenStreetMap contributors, ODbL.\n` +
  `insert into public.courts (osm_type, osm_id, name, lat, lng, court_type, type_source, hoops, area_m2, access, member_count, member_osm_ids) values\n` +
  rows.join(',\n') +
  `\non conflict (osm_type, osm_id) do update set name = excluded.name, lat = excluded.lat, lng = excluded.lng,\n` +
  `  court_type = excluded.court_type, type_source = excluded.type_source, hoops = excluded.hoops,\n` +
  `  area_m2 = excluded.area_m2, access = excluded.access, member_count = excluded.member_count, member_osm_ids = excluded.member_osm_ids;\n`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, sql);
console.log(JSON.stringify({ input, out, pitches, sites: sites.length, skipped, ...summarize(sites) }, null, 2));
